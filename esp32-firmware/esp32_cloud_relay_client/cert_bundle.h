/**
 * Initializes the system clock to a valid epoch timestamp (November 2026)
 * if the RTC currently reads earlier than 2025.
 */
static inline void ensureSaneSystemClock() {
    time_t now = time(nullptr);
    if (now < 1735689600UL) { // If RTC is before Jan 1, 2025
        struct timeval tv;
        tv.tv_sec = BASELINE_EPOCH_NOV_2026;
        tv.tv_usec = 0;
        settimeofday(&tv, nullptr);
        Serial.println("🕒 [TIME] Initialized baseline system clock (Nov 2026) for instant TLS validation.");
    }
}

